"""Build fresh paired instruction families with an unchanged external heldout.

Programmatic examples contrast operations on the same content. Public examples
retain their source metadata and end only at a real, complete assistant EOS.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import random
import string

try:
    from .prepare_instruction_advance import PARAPHRASES, select_public
    from .prepare_recovery_curriculum import (
    RESERVED_PROBES, SPECIAL, TEMPLATES, answer_for, normalized_prompt,
        parse_conversation, stable_hash, verify_generated_splits, write_jsonl,
    )
except ImportError:
    from prepare_instruction_advance import PARAPHRASES, select_public
    from prepare_recovery_curriculum import (
        RESERVED_PROBES, SPECIAL, TEMPLATES, answer_for, normalized_prompt,
        parse_conversation, stable_hash, verify_generated_splits, write_jsonl,
    )


PROTOCOL = "uttt-instruction-expansion-v1"
SOURCE = "uttt:paired-instruction-expansion-v1"
STRING_TASKS = ("copy", "uppercase", "lowercase", "reverse", "length")
STRING_BANDS = ((1, 4), (5, 8), (9, 16), (17, 24))


def digest(path):
    result = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            result.update(block)
    return result.hexdigest()


def read_jsonl(path):
    with Path(path).open(encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def semantic_key(task, arguments):
    return stable_hash(json.dumps({"task": task, "arguments": arguments}, sort_keys=True,
                                  ensure_ascii=False, separators=(",", ":")))


def _display(arguments):
    values = dict(arguments)
    for name in ("values", "object"):
        if name in values:
            values[name] = json.dumps(values[name], ensure_ascii=False, separators=(",", ":"))
    return values


def make_record(task, arguments, family, language, seed, difficulty):
    pool = (TEMPLATES[task][language][0], *PARAPHRASES[task][language])
    if TEMPLATES[task][language][1] in pool:
        raise ValueError("Heldout wording must not appear in a training pool")
    index = int(stable_hash(f"wording:{seed}:{family}:{task}:{language}")[:16], 16) % len(pool)
    prompt = pool[index].format(**_display(arguments))
    answer = answer_for(task, arguments)
    operands = ([arguments["a"], arguments["b"]] if task in {"add", "subtract", "multiply"}
                else list(arguments["values"]) if task == "sort" else [])
    payloads = ([arguments["text"]] if task in STRING_TASKS
                else list(arguments["object"].values()) if task == "extract" else [])
    return {
        "text": f"<|user|> {prompt}\n<|assistant|> {answer}<|eos|>",
        "source": SOURCE, "copyright": "Programmatically generated by this repository; no external text copied.",
        "protocol": PROTOCOL, "split": "train", "task": task, "language": language,
        "arguments": arguments, "operands": operands, "payloads": payloads,
        "semantic_key": semantic_key(task, arguments), "validation_group_id": family,
        "template_id": f"{task}.{language}.expansion.{index}", "prompt": prompt,
        "answer": answer, "difficulty": difficulty,
    }


def generate_families(parent_synthetic, heldout, *, seed, string_families, arithmetic_families, other_rows):
    """Generate fresh arguments; all languages/operations in a family share a group."""
    rng = random.Random(seed)
    parent_keys = {row["semantic_key"] for row in parent_synthetic}
    blocked_payloads = {str(value).casefold() for row in [*parent_synthetic, *heldout]
                        for value in row["payloads"]}
    blocked_payloads.update(("hello",))
    blocked_operands = {int(value) for row in heldout for value in row["operands"]}
    used_payloads = set(blocked_payloads)
    reserved = {normalized_prompt(value) for value in RESERVED_PROBES}
    reserved.update(normalized_prompt(row["prompt"]) for row in heldout)
    records = []

    def allocate_payload(bounds):
        for _ in range(100000):
            value = "".join(rng.choice(string.ascii_letters) for _ in range(rng.randint(*bounds)))
            if value.casefold() not in used_payloads:
                used_payloads.add(value.casefold())
                return value
        raise RuntimeError("Unable to allocate a new, disjoint payload")

    def append(task, arguments, family, difficulty):
        if semantic_key(task, arguments) in parent_keys:
            raise ValueError("Expansion reused a parent synthetic semantic case")
        for language in ("en", "zh"):
            record = make_record(task, arguments, family, language, seed, difficulty)
            if normalized_prompt(record["prompt"]) in reserved:
                raise ValueError("Generated prompt overlaps heldout/reserved probes")
            records.append(record)

    length_bands = Counter()
    for index in range(string_families):
        bounds = STRING_BANDS[index % len(STRING_BANDS)]
        value = allocate_payload(bounds)
        family = "expansion:string:" + stable_hash(value.casefold())
        difficulty = f"characters_{bounds[0]}_{bounds[1]}"
        length_bands[difficulty] += 1
        for task in STRING_TASKS:
            append(task, {"text": value}, family, difficulty)

    old_pairs = {tuple(sorted((int(row["arguments"]["a"]), int(row["arguments"]["b"]))))
                 for row in parent_synthetic if row["task"] in {"add", "subtract", "multiply"}}
    old_pairs.update(tuple(sorted((int(row["arguments"]["a"]), int(row["arguments"]["b"]))))
                     for row in heldout if row["task"] in {"add", "subtract", "multiply"})
    small_numbers = [number for number in range(100) if number not in blocked_operands]
    small_pool = [(a, b) for index, a in enumerate(small_numbers) for b in small_numbers[index:]
                  if (a, b) not in old_pairs and (a, b) != (1, 1)]
    rng.shuffle(small_pool)
    small_requested = arithmetic_families // 4
    small_count = min(small_requested, len(small_pool))
    pairs = [(pair, "arithmetic_0_99") for pair in small_pool[:small_count]]
    used_pairs = set(old_pairs) | {pair for pair, _ in pairs}
    expanded_numbers = [number for number in range(100, 1000) if number not in blocked_operands]
    remaining = arithmetic_families - small_count
    available_expanded = len(expanded_numbers) * (len(expanded_numbers) + 1) // 2
    available_expanded -= sum(a in expanded_numbers and b in expanded_numbers for a, b in used_pairs)
    if remaining > available_expanded:
        raise ValueError("Requested arithmetic families exceed the available new pair domain")
    for _ in range(remaining):
        for _attempt in range(100000):
            pair = tuple(sorted((rng.choice(expanded_numbers), rng.choice(expanded_numbers))))
            if pair not in used_pairs:
                used_pairs.add(pair)
                pairs.append((pair, "arithmetic_100_999"))
                break
        else:
            raise RuntimeError("Unable to allocate a fresh expanded arithmetic pair")
    for index, ((lo, hi), difficulty) in enumerate(pairs):
        # Both subtraction signs occur; commutative tasks retain the same family.
        a, b = ((lo, hi) if index % 2 == 0 else (hi, lo))
        family = "expansion:arithmetic:" + stable_hash(json.dumps([lo, hi], separators=(",", ":")))
        for task in ("add", "subtract", "multiply"):
            append(task, {"a": a, "b": b}, family, difficulty)

    other_families = other_rows // 2
    allowed_numbers = [number for number in range(1000) if number not in blocked_operands]
    seen_other = {("sort", stable_hash(json.dumps(sorted(row["arguments"]["values"]), separators=(",", ":"))))
                  for row in parent_synthetic if row["task"] == "sort"}
    for index in range(other_families):
        task = "sort" if index % 2 == 0 else "extract"
        for _attempt in range(100000):
            if task == "sort":
                values = rng.sample(allowed_numbers, rng.randint(2, 6))
                arguments = {"values": values}
                identity = stable_hash(json.dumps(sorted(values), separators=(",", ":")))
            else:
                obj = {key: allocate_payload((6, 16)) for key in ("name", "color", "code")}
                arguments = {"object": obj, "field": rng.choice(tuple(obj))}
                identity = stable_hash(json.dumps(obj, sort_keys=True, separators=(",", ":")))
            if (task, identity) not in seen_other and semantic_key(task, arguments) not in parent_keys:
                seen_other.add((task, identity))
                break
        else:
            raise RuntimeError("Unable to allocate a fresh sort/extract family")
        append(task, arguments, f"expansion:{task}:" + identity, "sort_2_6" if task == "sort" else "extract_3_fields")
    report = {
        "string_families": string_families, "string_families_by_length_band": dict(sorted(length_bands.items())),
        "arithmetic_families": arithmetic_families,
        "small_arithmetic_requested": small_requested, "small_arithmetic_available": len(small_pool),
        "small_arithmetic_selected": small_count, "small_arithmetic_redirected_to_new_domain": small_requested - small_count,
        "expanded_arithmetic_selected": arithmetic_families - small_count,
        "other_families": other_families,
        "blocked_parent_payloads": len(blocked_payloads), "blocked_heldout_operands": sorted(blocked_operands),
        "parent_semantic_overlap": len({row["semantic_key"] for row in records} & parent_keys),
        "new_semantic_cases": len({row["semantic_key"] for row in records}),
        "by_task_language": dict(sorted(Counter(row["task"] + ":" + row["language"] for row in records).items())),
        "by_template": dict(sorted(Counter(row["template_id"] for row in records).items())),
    }
    return records, report


def longest_complete_prefix(text, length_fn, max_tokens):
    """Return the longest source prefix ending at an existing assistant EOS."""
    turns = parse_conversation(text)
    stripped = text.strip()
    if length_fn(stripped) <= max_tokens:
        return stripped, len(turns), len(turns)
    ends = [match.end() for match in SPECIAL.finditer(text) if match.group() == "<|eos|>"]
    for kept in range(len(ends), 0, -1):
        candidate = text[:ends[kept - 1]].strip()
        if length_fn(candidate) <= max_tokens:
            if len(parse_conversation(candidate)) != kept:
                raise AssertionError("Source prefix lost a complete dialogue turn")
            return candidate, kept, len(turns)
    return None, 0, len(turns)


def prepare_public(path, heldout, parent_rows, *, count, seed, max_tokens, length_fn, previous_rows=None):
    candidates, rejected = [], Counter()
    input_hash = hashlib.sha256()
    parent_public_texts = {stable_hash(row["text"].strip()) for row in parent_rows
                           if not (row.get("task") and row.get("semantic_key"))}
    with Path(path).open("rb") as stream:
        for line_number, raw in enumerate(stream, 1):
            input_hash.update(raw)
            if not raw.strip():
                continue
            try:
                row = json.loads(raw)
                if not isinstance(row, dict):
                    raise ValueError("record_not_object")
                text = row.get("text")
                if not isinstance(text, str):
                    raise ValueError("missing_text")
                prefix, kept, original = longest_complete_prefix(text, length_fn, max_tokens)
                if prefix is None:
                    rejected["no_complete_prefix_within_budget"] += 1
                    continue
                if any(key in row for key in ("expansion_parent_text_sha256", "expansion_extraction")):
                    raise ValueError("reserved_expansion_metadata_collision")
                first_user = parse_conversation(prefix)[0][0]
                parent_hash = stable_hash(text)
                candidates.append({**row, "text": prefix,
                                   "validation_group_id": "public-first-user:" + stable_hash(normalized_prompt(first_user)),
                                   "expansion_parent_text_sha256": parent_hash,
                                   "expansion_extraction": {"protocol": "complete-prefix-v1", "source_line": line_number,
                                                            "original_turns": original, "kept_turns": kept,
                                                            "full_conversation": kept == original,
                                                            "original_characters": len(text), "kept_characters": len(prefix)}})
            except (ValueError, TypeError, UnicodeDecodeError) as error:
                rejected[str(error) if not isinstance(error, json.JSONDecodeError) else "invalid_json"] += 1
    selected, selection = select_public(candidates, count, seed, length_fn, max_tokens, heldout)
    selection.update(input_sha256=input_hash.hexdigest(), prefix_rejected=dict(sorted(rejected.items())),
                     eligible_prefixes_before_exclusions=len(candidates),
                     selected_full_conversations=sum(row["expansion_extraction"]["full_conversation"] for row in selected),
                     selected_shortened_prefixes=sum(not row["expansion_extraction"]["full_conversation"] for row in selected),
                     selected_multi_turn=sum(row["expansion_extraction"]["kept_turns"] > 1 for row in selected),
                     selected_text_previously_in_parent=sum(stable_hash(row["text"].strip()) in parent_public_texts for row in selected),
                     validation_group_policy="normalized_first_user_v1")
    selection["selected_text_previously_in_additional_data"] = {
        str(name): sum(stable_hash(row["text"].strip()) in hashes for row in selected)
        for name, hashes in (previous_rows or {}).items()}
    return selected, selection


def prepare(parent, public_path, output, tokenizer=None, *, seed=20261107, string_families=4000,
            arithmetic_families=4000, other_rows=4000, public_count=32000, max_tokens=512,
            validation_fraction=.02, length_fn=None, previous_data_paths=()):
    parent, public_path, output = Path(parent), Path(public_path), Path(output)
    if output.exists():
        raise FileExistsError(f"Refusing existing output: {output}")
    counts = (string_families, arithmetic_families, other_rows, public_count)
    if any(not isinstance(value, int) or isinstance(value, bool) or value < 0 for value in counts):
        raise ValueError("Family and public counts must be nonnegative integers")
    if other_rows % 2 or max_tokens < 16 or not 0 <= validation_fraction < 1:
        raise ValueError("Require even other_rows, max_tokens >= 16, validation fraction in [0,1)")
    tokenizer_hash = None
    if length_fn is None:
        if tokenizer is None:
            raise ValueError("An actual BPE tokenizer is required")
        from tokenizers import Tokenizer
        tokenizer_hash = digest(tokenizer)
        backend = Tokenizer.from_file(str(tokenizer))
        backend.no_padding()
        backend.no_truncation()
        length_fn = lambda text: len(backend.encode(text, add_special_tokens=False).ids) + 2
    input_rows = read_jsonl(parent / "train.jsonl")
    heldout = read_jsonl(parent / "heldout.jsonl")
    monitor = read_jsonl(parent / "eval_tasks.jsonl")
    old_synthetic = [row for row in input_rows if row.get("task") and row.get("semantic_key")]
    if not old_synthetic or not heldout or not monitor:
        raise ValueError("Parent requires synthetic training, heldout and monitor records")
    verify_generated_splits(old_synthetic, heldout)
    generated, generation = generate_families(
        old_synthetic, heldout, seed=seed, string_families=string_families,
        arithmetic_families=arithmetic_families, other_rows=other_rows)
    split_checks = verify_generated_splits(generated, heldout)
    if generation["parent_semantic_overlap"]:
        raise AssertionError("Parent semantic cases must not be reused")
    lengths = [length_fn(row["text"]) for row in generated]
    if any(value > max_tokens for value in lengths):
        raise ValueError("A generated instruction exceeds the token budget")
    public, public_stats = prepare_public(public_path, heldout, input_rows, count=public_count,
                                         seed=seed, max_tokens=max_tokens, length_fn=length_fn,
                                         previous_rows={str(Path(path).resolve()): {stable_hash(row["text"].strip())
                                                        for row in read_jsonl(path)} for path in previous_data_paths})
    train = [*generated, *public]
    if not train or len({row["text"] for row in train}) != len(train):
        raise ValueError("Require nonempty, duplicate-free training texts")
    if any(parse_conversation(row["text"]) != [(row["prompt"], answer_for(row["task"], row["arguments"]))]
           for row in generated):
        raise AssertionError("Generated reference mismatch")
    random.Random(seed + 1).shuffle(train)
    all_lengths = [*lengths, *(length_fn(row["text"]) for row in public)]
    groups = {row["validation_group_id"] for row in train}
    validation_groups = {group for group in groups if
                         int(stable_hash(f"group-validation-v1:{seed}:{group}")[:16], 16) / 2**64 < validation_fraction}
    validation_rows = sum(row["validation_group_id"] in validation_groups for row in train)
    parent_hashes = {name: digest(parent / name) for name in ("train.jsonl", "heldout.jsonl", "eval_tasks.jsonl", "manifest.json")}
    output.mkdir(parents=True, exist_ok=False)
    files = {"train.jsonl": write_jsonl(output / "train.jsonl", train)}
    for name in ("heldout.jsonl", "eval_tasks.jsonl", "upstream_sources.json"):
        if (parent / name).is_file():
            content = (parent / name).read_bytes()
            with (output / name).open("xb") as destination:
                destination.write(content)
            files[name] = {"sha256": digest(output / name), "bytes": len(content)}
            if name in parent_hashes and files[name]["sha256"] != parent_hashes[name]:
                raise AssertionError("Heldout/monitor bytes changed")
    report = {
        "protocol": PROTOCOL, "status": "complete", "seed": seed, "max_tokens": max_tokens,
        "builder_sha256": digest(__file__), "reference_builder_sha256": digest(answer_for.__code__.co_filename),
        "wording_builder_sha256": digest(Path(__file__).with_name("prepare_instruction_advance.py")),
        "parent": str(parent.resolve()), "parent_sha256": parent_hashes,
        "public_source": str(public_path.resolve()), "tokenizer_sha256": tokenizer_hash,
        "previous_data_sha256": {str(Path(path).resolve()): digest(path) for path in previous_data_paths},
        "token_measurement": "actual_BPE_plus_conservative_BOS_EOS" if tokenizer_hash else "injected_test_length",
        "train_records": len(train), "synthetic_train_records": len(generated), "public_train_records": len(public),
        "heldout_records": len(heldout), "monitor_records": len(monitor),
        "generation": generation, "public": public_stats, "generated_split_checks": split_checks,
        "internal_validation": {"group_key": "validation_group_id", "group_hash_protocol": "group-validation-v1",
                                "seed": seed, "validation_fraction": validation_fraction, "groups": len(groups),
                                "training_groups": len(groups) - len(validation_groups), "validation_groups": len(validation_groups),
                                "group_overlap": 0, "training_rows": len(train) - validation_rows,
                                "validation_rows": validation_rows},
        "all_token_lengths": {"min": min(all_lengths), "max": max(all_lengths),
                              "mean": sum(all_lengths) / len(all_lengths),
                              "rounded_32_histogram": dict(sorted(Counter(str(((value + 31) // 32) * 32)
                                                                          for value in all_lengths).items()))},
        "files": files,
        "notes": [
            "Fresh string content is shared across five operations and both languages; each whole content family stays in one validation group.",
            "Fresh arithmetic pairs are shared across three operations and both languages; neither orientation reuses a parent arithmetic pair.",
            "Parent heldout and monitor bytes, heldout wordings, individual operands and payloads remain excluded from generated training.",
            "Public source records retain metadata; selected text is a complete original prefix ending at a real EOS, never a truncated answer.",
            "All public prefixes/answers sharing the normalized first user instruction share their validation group.",
            "Public exact heldout/reserved prompts and exact ASCII heldout payload words are excluded; broader semantic/numeric public contamination is not claimed absent.",
            "Public sampling is bounded by available complete-prefix capacity; previously seen public text is reported, not silently counted as new.",
            "This curriculum does not replace broad pretraining or establish general assistant/online-memory quality.",
        ],
    }
    with (output / "manifest.json").open("x", encoding="utf-8", newline="\n") as stream:
        json.dump(report, stream, ensure_ascii=False, indent=2, sort_keys=True)
        stream.write("\n")
    return report


