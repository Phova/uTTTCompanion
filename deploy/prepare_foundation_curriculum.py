def coding_lesson(behavior, args, *, language=None, explain=False):
    """Return known source, a separate Python reference, boundary inputs, and prose."""
    if behavior == "affine":
        a, b = args["a"], args["b"]
        name, parameters, expression = "scale_and_shift", "value", f"{a} * value + ({b})"
        fn, inputs = lambda value: a * value + b, [[value] for value in (-5, -1, 0, 1, 4, 9)]
        en, zh = f"Return {a} times value plus {b}.", f"返回value乘{a}后加{b}的结果。"
    elif behavior == "clamp":
        low, high = args["low"], args["high"]
        name, parameters = "limit_value", "value"
        expression = f"{low} if value < {low} else ({high} if value > {high} else value)"
        fn = lambda value: max(low, min(high, value))
        inputs = [[value] for value in sorted({low - 2, low, low + 1, high - 1, high, high + 2})]
        en, zh = f"Clamp value to the closed interval [{low}, {high}].", f"把value限制在闭区间[{low}, {high}]内，超出边界时返回对应边界。"
    elif behavior == "interval":
        low, high, left, right = args["low"], args["high"], args["include_low"], args["include_high"]
        name, parameters = "inside_interval", "value"
        lsign, rsign = ("<=" if left else "<"), ("<=" if right else "<")
        expression = f"{low} {lsign} value {rsign} {high}"
        fn = lambda value: (value >= low if left else value > low) and (value <= high if right else value < high)
        inputs = [[value] for value in sorted({low - 1, low, low + 1, high - 1, high, high + 1})]
        en = f"Return whether value is in {'[' if left else '('}{low}, {high}{']' if right else ')'}. Square brackets include an endpoint; parentheses exclude it."
        zh = f"判断value是否属于{'[' if left else '('}{low}, {high}{']' if right else ')'}，返回布尔值；方括号包含端点，圆括号不包含端点。"
    elif behavior == "mod_equals":
        divisor, remainder = args["divisor"], args["remainder"]
        name, parameters, expression = "has_remainder", "number", f"number % {divisor} == {remainder}"
        fn = lambda number: number % divisor == remainder
        inputs = [[value] for value in (-divisor - 1, -divisor, -1, 0, 1, divisor, divisor + remainder)]
        en, zh = f"Using Python's % semantics, return whether number modulo {divisor} equals {remainder}.", f"按Python的%运算规则，判断number除以{divisor}的余数是否等于{remainder}，返回布尔值。"
    elif behavior == "length_test":
        op, limit = args["operator"], args["limit"]
        name, parameters = "check_length", "sequence"
        sign = {"eq": "==", "ge": ">=", "lt": "<"}[op]
        expression = f"len(sequence) {sign} {limit}"
        fn = lambda sequence: {"eq": len(sequence) == limit, "ge": len(sequence) >= limit, "lt": len(sequence) < limit}[op]
        inputs = [[value] for value in ("", "a", [], [None, 2], "x" * max(0, limit - 1), "x" * limit, "x" * (limit + 1))]
        en, zh = f"sequence is a string or list. Return whether len(sequence) {sign} {limit}.", f"sequence为字符串或列表，返回len(sequence) {sign} {limit}是否成立。"
    elif behavior == "nth_default":
        index, default = args["index"], args["default"]
        name, parameters = "item_or_default", "items"
        expression = f"items[{index}] if -len(items) <= {index} < len(items) else {default!r}"
        fn = lambda items: items[index] if -len(items) <= index < len(items) else default
        inputs = [[value] for value in ([], [7], [7, 9], [1, 2, 3, 4, 5], ["a", "b"], [None])]
        en, zh = f"Return the item at Python index {index}; if that index is out of range, return {default!r}.", f"返回列表items中Python索引{index}处的元素；索引越界时返回{default!r}，负索引按Python规则处理。"
    elif behavior == "slice_text":
        side, length = args["side"], args["length"]
        name, parameters = "take_text", "text"
        expression = f"text[:{length}]" if side == "prefix" or length == 0 else f"text[-{length}:]"
        fn = (lambda text: text[:length]) if side == "prefix" else (lambda text: "" if length == 0 else text[len(text) - min(length, len(text)):])
        inputs = [[value] for value in ("", "a", "abcd", "你好呀", "a b", "x" * (length + 1))]
