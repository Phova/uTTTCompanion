def load_exclusions(paths):
    blocked_keys = {canonical_key("reasoning", "add", {"a": 1, "b": 1}),
                    canonical_key("reasoning", "weekday", {"weekday": "Tuesday", "offset": 2})}
    blocked_prompts = {normalized_prompt(prompt) for prompt in RESERVED_PROBES}
    code_cases, hashes = [], {}
    def visit(row):
        if isinstance(row, list):
            for value in row:
                visit(value)
            return
        if not isinstance(row, dict):
            return
        if isinstance(row.get("prompt"), str):
            blocked_prompts.add(normalized_prompt(row["prompt"]))
        for key in ("family", "semantic_key", "validation_group_id"):
            if isinstance(row.get(key), str):
                blocked_keys.add(row[key].removeprefix("foundation:"))
        if row.get("family") in LEGACY_REASON_FAMILIES:
            op, args = LEGACY_REASON_FAMILIES[row["family"]]
            blocked_keys.add(canonical_key("reasoning", op, args))
        arguments = row.get("arguments")
        if isinstance(arguments, dict):
            op = row.get("foundation_operation")
            behavior = row.get("foundation_behavior")
            if op:
                blocked_keys.add(canonical_key("reasoning", op, arguments))
            elif behavior:
                blocked_keys.add(canonical_key("coding", behavior, arguments))
            elif row.get("task") in ("add", "subtract", "multiply") and {"a", "b"}.issubset(arguments):
                blocked_keys.add(canonical_key("reasoning", row["task"], arguments))
        check = row.get("code_check")
        if isinstance(check, dict) and check.get("cases"):
            code_cases.append(check["cases"])
        for key, value in row.items():
            if key not in ("prompt", "text", "code_check", "arguments") and isinstance(value, (list, dict)):
                visit(value)
    for path in sorted({Path(item).resolve() for item in [*_default_exclusions(), *paths]}):
        content = path.read_bytes()
        hashes[str(path)] = hashlib.sha256(content).hexdigest()
        if path.suffix == ".jsonl":
            with path.open(encoding="utf-8") as stream:
                visit([json.loads(line) for line in stream if line.strip()])
        else:
            visit(json.loads(content.decode("utf-8")))
    return blocked_keys, blocked_prompts, code_cases, hashes


def _matches_heldout_cases(reference, code_cases):
    for cases in code_cases:
        try:
            if all(_same(reference(*case["args"]), case["expected"]) for case in cases):
                return True
        except (TypeError, ValueError, KeyError, IndexError, ZeroDivisionError):
            continue
    return False


def _balanced_specs(pools, required, seed, category):
    ranked = {name: sorted(values, key=lambda args: digest(f"{seed}:{canonical_key(category, name, args)}"))
              for name, values in pools.items()}
    if sum(map(len, ranked.values())) < required:
        raise ValueError("Insufficient distinct semantic families: " + json.dumps(
            {"category": category, "required": required, "available": {name: len(pool) for name, pool in ranked.items()}}))
    selected, positions = [], Counter()
    while len(selected) < required:
        for name in ranked:
            if positions[name] < len(ranked[name]) and len(selected) < required:
                selected.append((name, ranked[name][positions[name]]))
                positions[name] += 1
    return selected


