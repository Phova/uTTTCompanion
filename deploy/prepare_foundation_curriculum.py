        fn = lambda items: sorted(items, reverse=descending)
        inputs = [[value] for value in ([], [1], [3, -2, 3, 0], [2, 1], [0, 0])]
        en, zh = f"Return a new list sorted in {'descending' if descending else 'ascending'} order; preserve duplicate values.", f"返回一个按{'降序' if descending else '升序'}排列的新列表，保留重复值，不修改原列表。"
