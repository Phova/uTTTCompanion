def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def canonical_key(category, operation, arguments):
    args = dict(arguments)
    if category == "reasoning" and operation in ("add", "multiply", "max", "min"):
        args["a"], args["b"] = sorted((args["a"], args["b"]))
    if category == "reasoning" and operation == "order":
        args["values"] = sorted(args["values"])
    return digest(json.dumps([category, operation, args], ensure_ascii=False, sort_keys=True, separators=(",", ":")))


