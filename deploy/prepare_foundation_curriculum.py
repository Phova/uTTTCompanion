def reasoning_reference(operation, args, language="en"):
    if operation in ("add", "subtract", "multiply", "divide", "max", "min"):
        a, b = args["a"], args["b"]
        return str({"add": lambda: a + b, "subtract": lambda: a - b, "multiply": lambda: a * b,
                    "divide": lambda: a // b, "max": lambda: max(a, b), "min": lambda: min(a, b)}[operation]())
    if operation == "quantity":
        return str(args["initial"] + args["gained"] - args["removed"])
    if operation == "clock":
        minutes = (args["hour"] * 60 + args["minute"] + args["delta"]) % (24 * 60)
        return f"{minutes // 60:02d}:{minutes % 60:02d}"
    if operation == "weekday":
        index = (DAYS.index(args["weekday"]) + args["offset"]) % 7
        return (ZH_DAYS if language == "zh" else DAYS)[index]
    if operation == "boolean":
        left, right = args["left"], args["right"]
        return str({"and": lambda: left and right, "or": lambda: left or right, "xor": lambda: left != right}[args["operator"]]())
    if operation == "order":
        return str((min if args["query"] == "min" else max)(args["values"]))
    raise ValueError("Unknown reasoning operation: " + operation)


